package GerenciadoHashSets.ReproducaoMusica;

public class Musica {
    private String nome, atista;

    public Musica(String nome, String atista) {
        this.nome = nome;
        this.atista = atista;
    }

    public String getNome() {
        return nome;
    }

    public String getAtista() {
        return atista;
    }
}
